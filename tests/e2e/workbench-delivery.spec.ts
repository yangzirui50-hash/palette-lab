import { expect, test } from '@playwright/test'
import type { Locator, Page } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const fixture = path.resolve('tests/fixtures/palette-test.png')
const saved = (page: Page) => expect(page.locator('.project-save-state')).toHaveAttribute('data-save-state', 'saved', { timeout: 10000 })
async function custom(root: Locator, label: string, hex: string) {
  await root.getByRole('button', { name: `自定义${label}颜色`, exact: true }).click()
  await root.getByLabel(`输入${label}HEX`, { exact: true }).fill(hex)
  await root.getByRole('button', { name: `应用${label}色值`, exact: true }).click()
}
async function importSingle(page: Page) {
  await page.goto('/'); await page.locator('.workspace input[type=file]').setInputFiles(fixture)
  await expect(page.locator('.spatial-preview img')).toBeVisible()
}

test('validates HEX, retains manual candidates without source-area changes, and restores them', async ({ page }) => {
  await importSingle(page)
  const root = page.locator('.single-results'), source = await page.locator('.swatch-info strong').allTextContents()
  await custom(root, '页面背景', '#oops')
  await expect(root.locator('.role-custom-error')).toContainText('HEX')
  await expect(root.getByLabel('选择页面背景颜色', { exact: true })).toHaveValue('#0a0a0a')
  await root.getByLabel('输入页面背景HEX', { exact: true }).fill('#AbC')
  await root.getByLabel('输入页面背景HEX', { exact: true }).press('Enter')
  await expect(root.getByLabel('选择页面背景颜色', { exact: true })).toHaveValue('#aabbcc')
  await expect(root.locator('.preview-web')).toHaveCSS('--preview-bg', '#aabbcc')
  await expect(root.locator('.working-color-grid article')).toHaveCount(1)
  await expect(root.locator('.working-color-grid')).toContainText('无图像占比')
  expect(await page.locator('.swatch-info strong').allTextContents()).toEqual(source)
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  await custom(root, '海报底色', '#12ab34')
  await page.getByRole('button', { name: 'Web / UI', exact: true }).click()
  await saved(page); await page.reload()
  await expect(root.getByLabel('选择页面背景颜色', { exact: true })).toHaveValue('#aabbcc')
  await expect(root.locator('.working-color-grid article')).toHaveCount(2)
  await custom(root, '页面背景', '#123456')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(root.getByLabel('选择页面背景颜色', { exact: true })).toHaveValue('#aabbcc')
  await expect(root.locator('.working-color-grid article')).toHaveCount(2)
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(root.getByLabel('选择页面背景颜色', { exact: true })).toHaveValue('#123456')
})

