test('applies native-ROI colors with undo and source coordinates while keeping local shares scoped', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.workspace')).toBeVisible()
  await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = canvas.height = 2048
    const context = canvas.getContext('2d')!
    context.fillStyle = '#808080'; context.fillRect(0, 0, 2048, 2048)
    for (let x = 768; x < 896; x++) { context.fillStyle = x % 2 ? '#ff0000' : '#0000ff'; context.fillRect(x, 768, 1, 128) }
    const blob = await new Promise<Blob>(resolve => canvas.toBlob(value => resolve(value!)))
    const transfer = new DataTransfer(); transfer.items.add(new File([blob], 'local-colors.png', { type: 'image/png' }))
    const input = document.querySelector<HTMLInputElement>('.workspace input[type=file]')!; input.files = transfer.files; input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(page.locator('.spatial-preview img')).toBeVisible()
  const source = await page.locator('.swatch-info strong').allTextContents()
  await page.locator('.spatial-roi-actions button').first().click()
  await page.locator('.spatial-image-stage').scrollIntoViewIfNeeded()
  const stage = await page.locator('.spatial-image-stage').boundingBox()
  if (!stage) throw new Error('Missing region stage')
  await page.mouse.move(stage.x + stage.width * .375, stage.y + stage.height * .375); await page.mouse.down()
  await page.mouse.move(stage.x + stage.width * .4375, stage.y + stage.height * .4375, { steps: 4 }); await page.mouse.up()
  await expect(page.locator('.spatial-detail')).toBeVisible()
  const local = await page.locator('.spatial-swatches button span').allTextContents(), hex = local.find(hex => !source.includes(hex))
  if (!hex) throw new Error('Expected native detail absent from the global reduced palette')
  await page.locator('.spatial-swatches button').filter({ has: page.locator('span', { hasText: hex }) }).click()
  await page.getByRole('button', { name: '加入工作色板', exact: true }).click()
  await expect(page.locator('.working-color-grid')).toContainText(hex)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.working-color-grid article')).toHaveCount(0)
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(page.locator('.working-color-grid')).toContainText('局部采样')
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  await page.locator('.single-results').getByLabel('选择主视觉色颜色', { exact: true }).selectOption(hex)
  const x = await page.locator('.preview-poster').evaluate(element => Number.parseFloat((element as HTMLElement).style.getPropertyValue('--primary-x')))
  expect(x).toBeGreaterThanOrEqual(37.4); expect(x).toBeLessThanOrEqual(43.8)
  expect(await page.locator('.swatch-info strong').allTextContents()).toEqual(source)
  const request = page.waitForRequest('**/api/analysis')
  await page.getByRole('button', { name: '生成 AI 美学分析', exact: true }).click()
  const payload = (await request).postDataJSON()
  expect(payload.spatialScope).toMatchObject({ area: 'roi', coordinates: 'source' })
  const evidence = payload.spatial.find((region: { hex: string }) => region.hex === hex)
  expect(evidence.dominantCentroid.x).toBeGreaterThanOrEqual(.374)
  expect(evidence.dominantCentroid.x).toBeLessThanOrEqual(.438)
  expect(evidence.share).toBeCloseTo(.5, 1)
  await expect(page.locator('.analysis-report')).toBeVisible()
  await saved(page); await page.reload()
  await expect(page.locator('.single-results').getByLabel('选择主视觉色颜色', { exact: true })).toHaveValue(hex)
  await expect(page.locator('.working-color-grid')).toContainText(hex)
})

