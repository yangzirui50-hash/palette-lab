import { expect, test } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const fixture = path.resolve('tests/fixtures/palette-test.png')

test('keeps single-image manual choices in both domains through re-extraction and scoped reset', async ({ page }) => {
  await page.goto('/')
  await page.locator('.workspace input[type=file]').setInputFiles(fixture)
  await expect(page.locator('.spatial-preview img')).toBeVisible()
  await page.getByLabel('选择页面背景颜色', { exact: true }).selectOption('#4a90e2')
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  await page.getByLabel('选择海报底色颜色', { exact: true }).selectOption('#dfff4f')
  await page.getByRole('button', { name: 'Web / UI', exact: true }).click()
  for (let step = 0; step < 4; step++) await page.getByLabel('减少颜色数量', { exact: true }).click()
  await expect(page.locator('.count-control output')).toHaveText('2')
  await expect(page.locator('.palette-panel')).toHaveAttribute('aria-busy', 'false')
  const background = page.getByLabel('选择页面背景颜色', { exact: true })
  await expect(background).toHaveValue('#4a90e2')
  expect(await page.locator('.swatch-info strong').allTextContents()).not.toContain('#4a90e2')
  await expect(page.locator('.preview-web')).toHaveCSS('--preview-bg', '#4a90e2')
  const downloadEvent = page.waitForEvent('download')
  await page.locator('.export-actions button').nth(1).click()
  const download = await downloadEvent
  expect(JSON.parse(fs.readFileSync((await download.path())!, 'utf8')).roles.background).toBe('#4a90e2')
  await page.getByRole('button', { name: '恢复自动分配', exact: true }).click()
  await expect(background).not.toHaveValue('#4a90e2')
  await expect(page.getByRole('button', { name: '恢复自动分配', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  await expect(page.getByLabel('选择海报底色颜色', { exact: true })).toHaveValue('#dfff4f')
  await expect(page.getByRole('button', { name: '恢复自动分配', exact: true })).toBeEnabled()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.locator('.role-editor').screenshot({ path: 'test-results/manual-single-roles.png' })
})

test('keeps edits after a failed import and starts a new draft only after a valid replacement', async ({ page }) => {
  await page.goto('/')
  await page.locator('.workspace input[type=file]').setInputFiles(fixture)
  await expect(page.locator('.spatial-preview img')).toBeVisible()
  await page.getByLabel('选择页面背景颜色', { exact: true }).selectOption('#4a90e2')
  await page.locator('.workspace input[type=file]').setInputFiles({ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from('not an image') })
  await expect(page.locator('.error-message')).toBeVisible()
  await expect(page.getByLabel('选择页面背景颜色', { exact: true })).toHaveValue('#4a90e2')
  await page.locator('.workspace input[type=file]').setInputFiles(path.resolve('tests/fixtures/monochrome-test.png'))
  await expect(page.locator('.source-meta strong')).toHaveText('monochrome-test.png')
  await expect(page.getByLabel('选择页面背景颜色', { exact: true })).not.toHaveValue('#4a90e2')
  await expect(page.getByRole('button', { name: '恢复自动分配', exact: true })).toBeDisabled()
})

test('retains series drafts by domain and strategy and exports exceptions from the edited base', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '系列', exact: true }).click()
  await page.locator('.series-workspace input[type=file]').setInputFiles([fixture, fixture])
  await expect(page.locator('.series-thumbnail')).toHaveCount(2)
  await page.getByRole('button', { name: '检查图片：palette-test.png', exact: true }).nth(1).click()
  await page.getByRole('button', { name: '锁定页面背景', exact: true }).click()
  await page.getByRole('button', { name: '统一色组', exact: true }).click()
  const background = page.locator('.series-unify').getByLabel('选择页面背景颜色', { exact: true })
  await background.selectOption('#4a90e2')
  await expect(background.locator('option[value="#0a0a0a"]')).toHaveCount(1)
  await expect(page.locator('.series-exceptions')).toContainText('background #0a0a0a')
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  const canvas = page.locator('.series-unify').getByLabel('选择海报底色颜色', { exact: true })
  await canvas.selectOption('#dfff4f')
  await page.getByRole('button', { name: '跟随主图', exact: false }).click()
  await canvas.selectOption('#4a90e2')
  await page.getByRole('button', { name: '保留个性', exact: false }).click()
  await expect(canvas).toHaveValue('#dfff4f')
  await page.getByRole('button', { name: 'Web / UI', exact: true }).click()
  await expect(background).toHaveValue('#4a90e2')
  await page.getByRole('button', { name: '跟随主图', exact: false }).click()
  await background.selectOption('#dfff4f')
  await page.getByRole('button', { name: '保留个性', exact: false }).click()
  await expect(background).toHaveValue('#4a90e2')
  await page.getByRole('button', { name: '跟随主图', exact: false }).click()
  await expect(background).toHaveValue('#dfff4f')
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  await expect(page.getByRole('button', { name: '保留个性', exact: false })).toHaveAttribute('aria-pressed', 'true')
  await expect(canvas).toHaveValue('#dfff4f')
  await page.getByRole('button', { name: 'Web / UI', exact: true }).click()
  await expect(page.getByRole('button', { name: '跟随主图', exact: false })).toHaveAttribute('aria-pressed', 'true')
  await expect(background).toHaveValue('#dfff4f')
  await page.getByRole('button', { name: '设为主图', exact: true }).nth(1).click()
  await expect(background).toHaveValue('#dfff4f')
  await page.getByLabel('前移 palette-test.png', { exact: true }).nth(1).click()
  await expect(background).toHaveValue('#dfff4f')
  const downloadEvent = page.waitForEvent('download')
  await page.locator('.series-export-actions button').nth(1).click()
  const download = await downloadEvent
  const tokens = JSON.parse(fs.readFileSync((await download.path())!, 'utf8'))
  expect(tokens.roles.background).toBe('#dfff4f')
  expect(tokens.palette.some((color: { hex: string }) => color.hex === '#dfff4f')).toBe(true)
  expect(Object.values(tokens.exceptions)).toContainEqual({ background: '#0a0a0a' })
  await page.locator('.series-unify .role-editor').getByRole('button', { name: '恢复自动分配', exact: true }).click()
  await expect(background).toHaveValue('#0a0a0a')
  await page.getByRole('button', { name: '保留个性', exact: false }).click()
  await expect(background).toHaveValue('#4a90e2')
  await page.getByRole('button', { name: 'Art / Poster', exact: true }).click()
  await expect(canvas).toHaveValue('#dfff4f')
  await page.getByRole('button', { name: '跟随主图', exact: false }).click()
  await expect(canvas).toHaveValue('#4a90e2')
  await page.locator('.series-unify').screenshot({ path: 'test-results/manual-series-draft.png' })
})

test('keeps a series draft after partial removal but clears it when starting an empty series again', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '系列', exact: true }).click()
  const input = page.locator('.series-workspace input[type=file]')
  await input.setInputFiles([fixture, fixture])
  await expect(page.locator('.series-thumbnail')).toHaveCount(2)
  await page.getByRole('button', { name: '统一色组', exact: true }).click()
  const background = page.locator('.series-unify').getByLabel('选择页面背景颜色', { exact: true })
  await background.selectOption('#4a90e2')
  await page.getByLabel('移除 palette-test.png', { exact: true }).first().click()
  await expect(page.locator('.series-thumbnail')).toHaveCount(1)
  await input.setInputFiles(fixture)
  await expect(background).toHaveValue('#4a90e2')
  await page.getByLabel('移除 palette-test.png', { exact: true }).first().click()
  await page.getByLabel('移除 palette-test.png', { exact: true }).first().click()
  await expect(page.locator('.series-thumbnail')).toHaveCount(0)
  await input.setInputFiles([fixture, fixture])
  await expect(background).toHaveValue('#0a0a0a')
  await expect(page.locator('.series-unify').getByRole('button', { name: '恢复自动分配', exact: true })).toBeDisabled()
})
